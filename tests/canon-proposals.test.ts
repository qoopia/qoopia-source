import {test,expect} from 'bun:test';
import {runMigrations} from '../src/db/migrate.ts';
import {db} from '../src/db/connection.ts';
import {createWorkspace} from '../src/admin/workspaces.ts';
import {createAgent,setDreamer} from '../src/admin/agents.ts';
import {proposeCanon,listCanonProposals,decideCanonProposal} from '../src/services/canon-proposals.ts';
import {listCanons} from '../src/services/canon.ts';
import {setMemoryPolicy} from '../src/services/memory-policy.ts';

test('dreaming drafts stay out of context until owner review; decisions and retries never duplicate rules',()=>{
 runMigrations();const ws=createWorkspace({name:'Draft rules fixture'}),other=createWorkspace({name:'Other draft rules fixture'});
 const owner=createAgent({name:'draft-owner',workspaceSlug:ws.slug,type:'owner'}).id;
 const dreamer=createAgent({name:'draft-dreamer',workspaceSlug:ws.slug}).id;
 const ordinary=createAgent({name:'draft-ordinary',workspaceSlug:ws.slug}).id;
 const steward=createAgent({name:'draft-steward',workspaceSlug:ws.slug,type:'steward'}).id;
 const actor={agent_id:dreamer,type:'standard'},human={agent_id:owner,type:'owner'};
 const input={text:'Перед проверкой проверяй рабочую ветку.',reason:'Repeated synthetic preference.',source_refs:['session:synthetic:message-1'],idempotency_key:'synthetic-draft-1'};
 expect(()=>proposeCanon(ws.id,actor,input)).toThrow('appointed dreamer');
 setDreamer({workspace_id:ws.id,agent_id:dreamer,enabled:true,actor_id:owner});
 const p=proposeCanon(ws.id,actor,input).proposal;
 expect(p).toMatchObject({source:'dreaming',status:'pending'});
 expect(listCanons({workspace_id:ws.id,actor:human}).items).toHaveLength(0);
 expect(proposeCanon(ws.id,actor,input).proposal.id).toBe(p.id);
 expect(()=>proposeCanon(ws.id,actor,{...input,text:'Changed text'})).toThrow('different content');
 expect(()=>listCanonProposals(ws.id,ordinary)).toThrow('owner');
 expect(()=>decideCanonProposal(ws.id,{agent_id:steward,type:'steward'},p.id,true)).toThrow('owner');
 expect(()=>decideCanonProposal(other.id,human,p.id,true)).toThrow('owner');
 const accepted=decideCanonProposal(ws.id,human,p.id,true).proposal;
 expect(accepted.status).toBe('accepted');
 expect(decideCanonProposal(ws.id,human,p.id,true).proposal.canon_id).toBe(accepted.canon_id);
 expect(()=>decideCanonProposal(ws.id,human,p.id,false)).toThrow('already decided');
 expect(listCanons({workspace_id:ws.id,actor:human}).items).toMatchObject([{source:'dreaming',id:accepted.canon_id}]);
 const rejected=proposeCanon(ws.id,actor,{...input,text:'Ненужный синтетический черновик.',idempotency_key:'synthetic-draft-2'}).proposal;
 decideCanonProposal(ws.id,human,rejected.id,false);
 expect(listCanonProposals(ws.id,owner).items).toHaveLength(0);
 expect(listCanons({workspace_id:ws.id,actor:human}).items).toHaveLength(1);
 setMemoryPolicy({workspace_id:ws.id,agent_id:dreamer,mode:'manual',actor_id:owner});
 expect(()=>proposeCanon(ws.id,actor,{...input,idempotency_key:'manual-refusal'})).toThrow('Automatic memory');
 expect((db.query('SELECT COUNT(*) n FROM canon_proposals WHERE workspace_id=?').get(ws.id) as any).n).toBe(2);
});
